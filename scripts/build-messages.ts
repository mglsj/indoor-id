/**
 * Compiles the UI's messages (`messages/en.json`, inlang's message format, as Paraglide reads
 * it) into src/lib/i18n/generated/en.ts, a constant whose literal types let `msg()` check each
 * message's `{param}` names. Runs on `bun install` (the `prepare` script) and with
 * `bun run messages`; the output is not committed.
 *
 * Usage: bun scripts/build-messages.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "messages/en.json");
const out = join(root, "src/lib/i18n/generated");

const { $schema: _, ...messages } = JSON.parse(
	readFileSync(source, "utf8"),
) as Record<string, string>;

const KEY = /^[a-z][a-z0-9_]*$/;
for (const [key, text] of Object.entries(messages)) {
	if (!KEY.test(key)) throw new Error(`Message key ${key} is not snake_case`);
	if (typeof text !== "string") throw new Error(`Message ${key} is not text`);
}

mkdirSync(out, { recursive: true });
writeFileSync(
	join(out, "en.ts"),
	`// Generated by scripts/build-messages.ts from messages/en.json: edit that file instead.\nexport const EN = ${JSON.stringify(messages, null, "\t")} as const;\n`,
);
console.log(
	`Messages: ${Object.keys(messages).length} → src/lib/i18n/generated/`,
);
